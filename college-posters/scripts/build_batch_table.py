def rows_for(sid):
    d = json.loads((ROOT / "data" / f"{sid}.json").read_text(encoding="utf-8"))
    r = d["rankings"]
    poster = [
        ("首屏", "校名", f"{d['name']}（{d['short']}）", f"{d['name']} / {d['name_en']}"),
        ("首屏", "身份标签", " / ".join(d["tags"]), " / ".join(d["tags"])),
        ("首屏", "一句话定位", d["slogan"], d["slogan"]),
        ("首屏", "校训", f"{d['motto']}（{d.get('motto_note', '')}）", d["motto"]),
        ("速览", "速览", "；".join(f"{k}：{v}" for k, v in d["basic"]), f"创办{d['founded']}年；" + "；".join(v for _, v in d["basic"])),
        ("排名", "软科中国大学排名", f"{r[0]['value']}名（{r[0]['year']}）", f"{r[0]['value']}名"),
        ("排名", "QS世界大学排名", f"{r[1]['value']}名（{r[1]['year']}）", f"{r[1]['value']}名"),
        ("排名", "软科世界大学学术排名", f"{r[2]['value']}名（{r[2]['year']}）", f"{r[2]['value']}名"),
        ("排名", "第4张排名卡", f"{r[3]['label']} {r[3]['value']}{r[3]['unit']}（{r[3]['year']}）", f"{r[3]['value']}{r[3]['unit']}"),
        ("历史", "历史沿革", " → ".join(f"{y} {t}" for y, t in d["history"]), "4个节点"),
        ("学科", "双一流建设学科", "、".join(d["double_first"]), "、".join(d["double_first"])),
        ("学科", "学科评估亮点", d["eval_note"], d["eval_note"]),
        ("专业", "王牌专业", "、".join(d["majors"]), f"{len(d['majors'])}个"),
        ("专业", "以什么著称", d["known_for"], d["known_for"]),
        ("就业", "深造率", f"{d['career']['rate_label']} {d['career']['rate_value']}（{d['career']['rate_year']}）",
         f"{d['career']['rate_value']}（{d['career']['rate_year']}）"),
        ("就业", "就业方向", "、".join(d["career"]["directions"]), "3个方向"),
        ("人文", "知名校友", "；".join(f"{n}：{t}" for n, t in d["alumni"]), "；".join(f"{n} {t}" for n, t in d["alumni"])),
        ("人文", "校园风物", "；".join(f"{n}：{t}" for n, t in d["landmarks"]), "3项"),
        ("报考", "适合什么样的学生", "；".join(d["fit"]), "3条"),
        ("报考", "选科要求", "；".join(f"{k}：{v}" for k, v in d["subject_req"]), "2行"),
        ("页脚", "激励语", d["encourage"], d["encourage"]),
        ("页脚", "官网", d["website"], f"二维码 + {d['website_label']}"),
    ]
    out = []
    for mod, field, full, short in poster:
        src, st = DEFAULT[field]
        n = NOTES.get(sid, {}).get(field, {})
        out.append((mod, field, n.get("full", full), short, n.get("src", src), n.get("st", st)))
    return d["name"], out


def style(ws, widths):
    for c in ws[1]:
        c.font = Font(bold=True, color="FFFFFF")
        c.fill = PatternFill("solid", fgColor="0B6B3F")
    for row in ws.iter_rows(min_row=2):
        for c in row:
            c.alignment = Alignment(wrap_text=True, vertical="top")
            if isinstance(c.value, str) and c.value.startswith("待核"):
                c.fill = PatternFill("solid", fgColor="FFF2CC")
    for i, w in enumerate(widths):
        ws.column_dimensions[chr(65 + i)].width = w
    ws.freeze_panes = "A2"


wb = Workbook()
summary = wb.active
summary.title = "待核汇总"
summary.append(["学校", "字段", "当前内容", "核验状态"])
for sid in IDS:
    name, rows = rows_for(sid)
    ws = wb.create_sheet(name)
    ws.append(["模块", "字段", "全量内容", "海报内容", "来源", "核验状态"])
    for r in rows:
        ws.append(r)
        if r[5].startswith("待核"):
            summary.append([name, r[1], r[2], r[5]])
    style(ws, [8, 18, 60, 34, 34, 26])
style(summary, [16, 18, 70, 30])
dst = ROOT / "data" / f"字段表_{BATCH}.xlsx"
wb.save(dst)
print(dst, summary.max_row - 1, "项待核")
